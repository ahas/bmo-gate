CREATE TABLE public.document_translations (
    document text NOT NULL,
    version text NOT NULL,
    target text NOT NULL,
    part bigint NOT NULL,
    parts bigint NOT NULL,
    text text,
    failed bigint DEFAULT 0 NOT NULL,
    translated_at bigint NOT NULL,
    rowid bigint NOT NULL,
    failure text
);

ALTER TABLE public.document_translations ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.document_translations_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

